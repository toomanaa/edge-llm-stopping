#!/usr/bin/env python3
"""Build data/qa_v2.jsonl: ~1000 questions, ~40% factual (single-answer,
match_mode="any") and ~60% explain/why (multi-concept, match_mode="all").

Design note on why the mix isn't drawn from a literature benchmark: factoid
QA (NQ-open, TriviaQA, SQuAD) and non-factoid/explanatory QA (ANTIQUE,
WikiQA) are studied as separate benchmark categories in the literature,
not combined with an established ratio. The 60/40 explain-weighted split
here is a deliberate choice for THIS project's purpose: E1 (v1) showed
that "unsafe" (mid-answer) stopping boundaries are concentrated in
longer, elaborative answers, and explain/why questions are what reliably
produce those, so the dataset is weighted toward the question type that
actually exercises the phenomenon under study.

Each entry:
  id, question, type ("factual" | "explain"),
  answers (list of lowercase required strings),
  match_mode ("any" | "all")
"any": correct if the text contains at least one of `answers` (factual).
"all": correct if the text contains every one of `answers` (explain --
       each string is a short required concept/keyword).
"""
import json, random, itertools, pathlib

random.seed(20260826)
qa = []

def add_factual(q, *answers):
    qa.append({"question": q, "answers": [a.lower() for a in answers],
               "match_mode": "any", "type": "factual"})

def add_explain(q, *concepts):
    qa.append({"question": q, "answers": [c.lower() for c in concepts],
               "match_mode": "all", "type": "explain"})

