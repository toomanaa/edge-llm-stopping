# Only templates that are grammatically robust with gerund-phrase topics
# (e.g. "leaves changing color", "eclipses happening") are used. Templates
# like "Why does {t}?" were tried first and produced broken grammar
# ("Why does some clouds bring rain?") because they need a finite-clause
# object, not a noun phrase -- caught by inspection before shipping and
# replaced with templates that take a noun phrase correctly.
ALL_TEMPLATES = [
    "What causes {t}?",
    "Can you explain what causes {t}?",
    "Explain how {t} works.",
    "What is the reason behind {t}?",
]
for topic, concepts in topics:
    for tmpl in ALL_TEMPLATES:
        q = tmpl.format(t=topic)
        q = q[0].upper() + q[1:]
        add_explain(q, *concepts)

